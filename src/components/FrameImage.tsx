"use client";

import { useMemo, useSyncExternalStore } from "react";
import { thumbHashToDataURL } from "thumbhash";
import type { Frame } from "@/lib/frames";
import { pad } from "@/lib/format";

type Props = {
  frame: Frame;
  /** The `sizes` attribute for responsive selection. */
  sizes: string;
  priority?: boolean;
  className?: string;
  /** "cover" fills the box; "contain" letterboxes (lightbox). */
  fit?: "cover" | "contain";
  /** Hide the placeholder's own label when a HUD overlay already labels it. */
  bare?: boolean;
  /** Show only the blur placeholder for now; the photo itself loads when this turns false. */
  deferred?: boolean;
};

const block = (e: React.SyntheticEvent) => e.preventDefault();

const blurCache = new Map<string, string>();
const noop = () => () => {};

/** Blur placeholder for a thumbhash, available after hydration (so server and client markup match). */
function useBlur(hash: string | undefined) {
  const hydrated = useSyncExternalStore(
    noop,
    () => true,
    () => false,
  );
  return useMemo(() => {
    if (!hash || !hydrated) return undefined;
    let url = blurCache.get(hash);
    if (!url) {
      const bytes = Uint8Array.from(atob(hash), (c) => c.charCodeAt(0));
      url = thumbHashToDataURL(bytes);
      blurCache.set(hash, url);
    }
    return url;
  }, [hash, hydrated]);
}

/**
 * One frame. Real photos render as <picture> with AVIF/WebP srcsets over
 * their thumbhash blur.
 */
export function FrameImage({
  frame,
  sizes,
  priority = false,
  className = "",
  fit = "cover",
  bare = false,
  deferred = false,
}: Props) {
  // Decoded client-side only: the server render shows the dominant colour,
  // and the blur fills in on hydration.
  const blur = useBlur(frame.thumbhash);

  if (frame.kind === "photo") {
    return (
      <picture
        data-tone={frame.tone ?? frame.color}
        className={`protect relative block h-full w-full ${className}`}
        style={{
          backgroundColor: frame.color,
          backgroundImage: blur ? `url(${blur})` : undefined,
          backgroundSize: fit,
          backgroundPosition: "center",
        }}
        onContextMenu={block}
      >
        {!deferred && frame.avif && <source type="image/avif" srcSet={frame.avif} sizes={sizes} />}
        {!deferred && frame.webp && <source type="image/webp" srcSet={frame.webp} sizes={sizes} />}
        {!deferred && (
          // eslint-disable-next-line @next/next/no-img-element -- derivatives are pre-generated by the ingest pipeline
          <img
            src={frame.src}
            alt={frame.alt}
            width={frame.width}
            height={frame.height}
            loading={priority ? "eager" : "lazy"}
            fetchPriority={priority ? "high" : "auto"}
            decoding="async"
            draggable={false}
            onContextMenu={block}
            onDragStart={block}
            className={`h-full w-full ${fit === "cover" ? "object-cover" : "object-contain"}`}
          />
        )}
      </picture>
    );
  }

  // Placeholder or withheld: a flat tile in the right aspect ratio, so the
  // layout doesn't move when the original lands.
  return (
    <div role="img" aria-label={frame.alt} className={`relative flex h-full w-full items-end bg-ink-2 ${className}`}>
      {!bare && (
        <span className="micro p-3 text-paper-faint">
          {frame.kind === "withheld" ? "Withheld" : `${frame.collectionTitle} ${pad(frame.index, 2)}`}
        </span>
      )}
    </div>
  );
}
